export function seasonConfirmation(season) {
 const final = String(season).toUpperCase() === 'AUTUMN'
 return final ? {
  title: 'Завершить действия в партии?',
  message: 'После подтверждения вы больше не сможете действовать в этой партии. Подсчёт очков начнётся, когда соперник тоже завершит свои действия',
  action: 'Завершить действия',
 } : {
  title: 'Завершить сезон?',
  message: 'После подтверждения вы больше не сможете действовать в этом сезоне. Следующий начнётся, когда соперник тоже завершит свои действия',
  action: 'Завершить сезон',
 }
}
